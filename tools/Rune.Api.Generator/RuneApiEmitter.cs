                text.Append($"\n    public Task<{CSharpType(method.Result)}> {method.Name}({parameters}IRuneRpcTransport rpc) =>\n");
                text.Append($"        rpc.CallAsync<{CSharpType(method.Result)}>(\"{method.CanonicalId}\", RuneReceiver, new {{ ");
                text.Append(string.Join(", ", method.Parameters.Select(parameter => parameter.Name)));
                text.Append(" });\n");
            }
            text.Append("}\n\n");
        }
        return text.ToString();
    }

    private static string EmitJson(RuneApiModel model)
    {
        var document = new
        {
            package = model.Package,
            version = model.Version,
            netCordVersion = model.NetCordVersion,
            fingerprint = model.Fingerprint,
            types = model.Types.Select(type => new
            {
                type.Name,
                type.NetCordName,
                type.IsEnum,
                type.Base,
                members = type.Members.Select(member => new
                {
                    member.Name,
                    member.CanonicalId,
                    type = member.Type.Name,
                    member.Type.Optional,
                    member.Representation,
                    member.EnumValue
                }),
                methods = type.Methods.Select(method => new
                {
                    method.Name,
                    method.CanonicalId,
                    method.IsAsync,
                    parameters = method.Parameters,
                    result = method.Result
                })
            }),
            events = model.Events
        };

        return JsonSerializer.Serialize(
                   document,
                   new JsonSerializerOptions
                   {
                       WriteIndented = true,
                       PropertyNamingPolicy = JsonNamingPolicy.CamelCase
                   }) + "\n";
    }

    private static string EmitRpcJson(RuneApiModel model)
    {
        var calls = model.Types.SelectMany(type =>
            type.Methods.Select(method => new
            {
                id = method.CanonicalId,
                receiver = type.Name,
                asynchronous = method.IsAsync,
                parameters = method.Parameters.Select(parameter => new
                {
                    parameter.Name,
                    type = parameter.Type.Name,
                    parameter.Type.Optional
                }),
                result = new
                {
                    type = method.Result.Name,
                    method.Result.Optional
                }
            }));
        return JsonSerializer.Serialize(
                   new
                   {
                       apiVersion = model.Version,
                       model.Fingerprint,
                       transport = "microvm-rpc",
                       calls
                   },
                   new JsonSerializerOptions
                   {
                       WriteIndented = true,
                       PropertyNamingPolicy = JsonNamingPolicy.CamelCase
                   }) + "\n";
    }

    private static string EmitDocumentation(RuneApiModel model, string? language)
    {
        var text = new StringBuilder("<!-- <auto-generated by Rune.Api.Generator /> -->\n\n");
        var title = language is null ? "Rune.API reference" : $"Rune.API reference: {DisplayLanguage(language)}";
        text.Append($"# {title}\n\n");
        text.Append($"API `{model.Version}` · NetCord `{model.NetCordVersion}` · fingerprint `{model.Fingerprint}`\n\n");
        text.Append("Rune.API is a selected snapshot and method projection of NetCord. The initial surface does not expose fetching, arbitrary channel access, guild management, the Discord client, caches or general REST access.\n\n");
        text.Append("## Events\n\n");
        foreach (var gatewayEvent in model.Events)
            text.Append($"- `{gatewayEvent.Name}` receives `{gatewayEvent.Payload}` from `{gatewayEvent.NetCordName}`.\n");
        text.Append("\n## Types\n\n");

        foreach (var type in model.Types)
        {
            text.Append($"### {type.Name}\n\n");
            text.Append($"NetCord: `{type.NetCordName}`");
            if (type.Base is not null)
                text.Append($" · inherits `{type.Base}`");
            text.Append("\n\n");
            foreach (var member in type.Members)
                text.Append($"- `{ProjectedMember(member.Name, language)}` → `{member.CanonicalId}`\n");
            foreach (var method in type.Methods)
                text.Append($"- `{ProjectedMethod(method, language)}` → `{method.CanonicalId}`\n");
            text.Append('\n');
        }
        return text.ToString();
    }

    private static IReadOnlyList<RuneApiMember> AllMembers(RuneApiModel model, RuneApiType type)
    {
        var members = new List<RuneApiMember>();
        if (type.Base is not null)
        {
            var baseType = model.Types.Single(value => value.Name == type.Base);
            members.AddRange(AllMembers(model, baseType));
        }
        members.AddRange(type.Members);
        return members;
    }

    private static IReadOnlyList<RuneApiMethod> AllMethods(RuneApiModel model, RuneApiType type)
    {
        var methods = new List<RuneApiMethod>();
        if (type.Base is not null)
        {
            var baseType = model.Types.Single(value => value.Name == type.Base);
            methods.AddRange(AllMethods(model, baseType));
        }
        methods.AddRange(type.Methods);
        return methods;
    }

    private static string JavaScriptHydrate(RuneApiValueType type, string value)
    {
        if (type.Optional)
            return $"{value} == null ? null : {JavaScriptHydrate(type with { Optional = false }, value)}";
        if (type.IsSelectedType && type.Name != "ReactionType")
            return $"new {type.Name}({value})";
        if (type.Name == "u64")
            return $"BigInt({value})";
        return value;
    }

    private static string JavaScriptLower(RuneApiValueType type, string value)
    {
        if (!type.IsSelectedType || type.Name == "ReactionType")
            return value;
        var target = type.Name;
        return $"Object.fromEntries(Object.entries({value}).filter(([key]) => !key.startsWith(\"__rune\"))) /* {target} */";
    }

    private static string PythonHydrate(RuneApiValueType type, string value)
    {
        if (type.Optional)
            return $"None if {value} is None else {PythonHydrate(type with { Optional = false }, value)}";
        if (type.IsSelectedType && type.Name != "ReactionType")
            return $"{type.Name}({value})";
        return value;
    }

    private static string PythonLower(RuneApiValueType type, string value) => value;

    private static string RubyHydrate(RuneApiValueType type, string value)
    {
        if (type.IsSelectedType && type.Name != "ReactionType")
            return $"{type.Name}.new({value})";
        return value;
    }

    private static string CSharpType(RuneApiValueType type)
    {
        var value = type.Name switch
        {
            "u64" => "ulong",
            "bool" => "bool",
            "string" => "string",
            _ => type.Name
        };
        return type.Optional ? value + "?" : value;
    }

    private static string CSharpDefault(RuneApiValueType type) =>
        !type.Optional && (type.Name == "string" || type.IsSelectedType && type.Name != "ReactionType")
            ? " = default!;"
            : string.Empty;

    private static string TypeScriptType(RuneApiValueType type)
    {
        var value = type.Name switch
        {
            "u64" => "bigint",
            "bool" => "boolean",
            "string" => "string",
            _ => type.Name
        };
        return type.Optional ? value + " | null" : value;
    }

    private static string PythonType(RuneApiValueType type)
    {
        var value = type.Name switch
        {
            "u64" => "int",
            "bool" => "bool",
            "string" => "str",
            _ => type.Name
        };
        return type.Optional ? value + " | None" : value;
    }

    private static string RustType(RuneApiValueType type)
    {
        var value = type.Name switch
        {
            "u64" => "u64",
            "bool" => "bool",
            "string" => "String",
            _ => type.Name
        };
        return type.Optional ? $"Option<{value}>" : value;
    }

    private static string CType(RuneApiValueType type)
    {
        var value = type.Name switch
        {
            "u64" => "uint64_t",
            "bool" => "bool",
            "string" => "const char *",
            _ => $"rune_{Names.Snake(type.Name)}"
        };
        return type.Optional && type.Name is not "string" ? value : value;
    }

    private static string CppType(RuneApiValueType type)
    {
        var value = type.Name switch
        {
            "u64" => "std::uint64_t",
            "bool" => "bool",
            "string" => "std::string",
            _ => type.Name
        };
        return type.Optional ? $"std::optional<{value}>" : value;
    }

    private static string PythonMember(string name)
    {
        var value = Names.Snake(name);
        return value == "type" ? "type_" : value;
    }

    private static string RustMember(string name)
    {
        var value = Names.Snake(name);
        return value == "type" ? "type_" : value;
    }

    private static string ProjectedMember(string name, string? language) =>
        language switch
        {
            "javascript" or "typescript" => Names.Camel(name),
            "python" or "ruby" or "rust" or "c" or "cpp" => Names.Snake(name),
            _ => name
        };

    private static string ProjectedMethod(RuneApiMethod method, string? language)
    {
        var name = language switch
        {
            "csharp" => method.Name,
            "javascript" or "typescript" => Names.Camel(Names.WithoutAsync(method.Name)),
            _ => Names.Snake(Names.WithoutAsync(method.Name))
        };
        var parameters = string.Join(", ", method.Parameters.Select(parameter => ProjectedMember(parameter.Name, language)));
        return $"{name}({parameters})";
    }

    private static string DisplayLanguage(string language) =>
        language switch
        {
            "javascript" => "JavaScript",
            "typescript" => "TypeScript",
            "python" => "Python",
            "ruby" => "Ruby",
            "rust" => "Rust",
            "c" => "C",
            "cpp" => "C++",
            "csharp" => "C#",
            _ => language
        };
