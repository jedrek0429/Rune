            ["src/Rune.Core/Api/Generated/RuneApi.g.cs"] = EmitManagedModel(model)
        };

        foreach (var language in Languages)
        {
            output[$"docs/api/generated/{language}.md"] =
                EmitDocumentation(model, language);
        }

        return output;
    }

